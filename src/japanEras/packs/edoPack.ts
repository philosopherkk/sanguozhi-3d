function paint(year: number): Record<string, string> {
  const groups: [string[], string][] = [
    [['ezochi'], F.ainu],
    [['ryukyu'], F.ryukyu],
    [BAKURYO, F.bakufu],
  ]
  if (year >= 1604) groups.push([['matsumae'], F.matsumae])
  return paintDomains(groups, F.han)
}

