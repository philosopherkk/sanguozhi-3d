function fact(
  text: string,
  source: string,
  disputed?: boolean,
  note?: string,
) {
  if (disputed) {
    return note
      ? { text, source, disputed: true as const, note }
      : { text, source, disputed: true as const }
  }
  if (note) {
    return { text, source, note }
  }
  return { text, source }
}

