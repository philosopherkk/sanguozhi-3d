export function wuxiLegendNote(year: number): { text: string; source: string } {
  const atEnd =
    year >= 280 ? '280 年仍單獨著色，不併入西晉。' : ''
  return {
    text: `五溪蠻只表武陵、沅水上游羈縻，不是荊州全境。曹魏未曾領有武陵。其餘部族見「塞外部族」。${atEnd}`,
    source: '《後漢書·南蠻傳》；《宋書·夷蠻傳》',
  }
}
