import type { EraDetail, EraEvent, EraPerson, EraReading } from '../../japanEras/types'

/**
 * 人物連結欄位之紀律（沿用 task_0008／PR #95 於 `src/sengoku/data/timelineDetails.ts` 之慣例）：
 * `zhwikiUrl`／`jawikiUrl` 一律先以 MediaWiki `action=opensearch` 查得實際條目標題（標題之繁簡
 * 與字形變體以條目為準），再以 `action=query&redirects=1` 檢視回應中有無 `missing` 以確認條目
 * 存在，最後以 `action=query&prop=extracts&exintro=1` 抽取首段核對時代與身分，同名人物尤其不可
 * 憑姓名推斷。HTTP 狀態碼不可作為存在與否的依據：`zh.wikipedia.org/zh-tw/<不存在標題>` 對不存在
 * 之條目同樣回傳 200（落到「創建該條目」頁）。中文維基無條目而日文維基有條目時改填 `jawikiUrl`，
 * 並在 `note` 寫明「中文維基無條目，採日文條目」；兩者皆無條目則留空，並在 `note` 寫明原因，
 * 絕不憑空構造 URL。存在性之最終判定以 `npm run audit:wiki-links`（API 判定）為準。
 */
type WikiLinks<T> = T & {
  /** 中文維基條目（zh-tw 視窗；條目標題已經 API 確認存在） */
  zhwikiUrl?: string
  /** 中文維基無條目時改採的日文條目（已經 API 確認存在） */
  jawikiUrl?: string
}

/** 關鍵人物之連結欄位與選取理由（`EraDetail` 原本只有姓名與役割）。 */
type HeianKeyFigure = WikiLinks<EraDetail['keyFigures'][number]> & {
  /** 條目選取之理由：別名、重定向、同名異人、查無條目等 */
  note?: string
}

/** 只在既有形狀上增加連結欄位，不改變既有欄位之語意。 */
type HeianDetail = Omit<EraDetail, 'keyFigures'> & {
  keyFigures: HeianKeyFigure[]
  /**
   * 卡片層「延伸閱讀」。詳情卡的關鍵人物列表只渲染姓名與役割，未渲染個別連結，
   * 故人物連結在此並列（做法同 PR #95）；此欄位是否送出至卡片，取決於
   * `src/japanEras/EraTimeline.tsx` 的轉傳，目前該檔尚未轉傳，故暫時只在資料層就位。
   */
  furtherReading?: { label: string; url: string }[]
}

/** 人物卡：`note` 已由 `EraPeople` 渲染，連結欄位之選取理由寫入 `note`。 */
type HeianPerson = WikiLinks<EraPerson>

